import React from 'react';
import { DocumentLayout } from './DocumentLayout';
import { AcademicReportData } from '../../types/documentTemplates';

export interface AcademicReportTemplateProps {
  report: AcademicReportData;
  orientation?: 'portrait' | 'landscape';
  showSignatures?: boolean;
  signatureLabels?: string[];
  isForPreview?: boolean;
}

export const AcademicReportTemplate: React.FC<AcademicReportTemplateProps> = ({
  report,
  orientation = 'portrait',
  showSignatures = true,
  signatureLabels = ['Subject Faculty', 'Academic Coordinator', 'Center Director / Principal'],
  isForPreview: _isForPreview = false,
}) => {
  const {
    reportTitle,
    reportCategory,
    metadata,
    summaryMetrics,
    tableData,
    customSections,
    chartSummary,
    recommendations,
    customFooterNote,
  } = report;

  return (
    <DocumentLayout
      documentTitle={reportTitle}
      documentSubtitle={`Infinite Tutorial Certified Evaluation Ledger • ${reportCategory}`}
      reportCategory={reportCategory}
      metadata={metadata}
      orientation={orientation}
      showSignatures={showSignatures}
      signatureLabels={signatureLabels}
      customFooterNote={customFooterNote || 'Certified Academic Record generated by Infinite Tutorial Academic ERP'}
    >
      {/* 1. Summary KPI Metric Cards Strip */}
      {summaryMetrics && summaryMetrics.length > 0 && (
        <section className="grid grid-cols-2 sm:grid-cols-4 gap-3 avoid-break">
          {summaryMetrics.map((metric, idx) => (
            <div
              key={idx}
              className="metric-kpi-card bg-slate-50 border border-slate-300 rounded-lg p-2.5 text-center"
            >
              <span className="text-[10px] font-bold uppercase tracking-wider text-slate-500 block">
                {metric.label}
              </span>
              <div
                className={`text-lg font-black mt-0.5 ${
                  metric.color || 'text-[#0A3622]'
                }`}
              >
                {metric.value}
              </div>
              {metric.subtext && (
                <span className="text-[9.5px] text-slate-600 block mt-0.5">
                  {metric.subtext}
                </span>
              )}
            </div>
          ))}
        </section>
      )}

      {/* 2. Structured Data Table (with repeating thead for clean page breaks) */}
      {tableData && tableData.columns.length > 0 && (
        <section className="doc-section-card border border-slate-300 rounded-lg overflow-hidden bg-white avoid-break">
          <table className="w-full text-xs text-left border-collapse">
            <thead className="bg-[#F0FDF4] border-b border-[#166534]/30 text-[#0A3622] font-black uppercase tracking-wider text-[10px]">
              <tr>
                {tableData.columns.map((col) => (
                  <th
                    key={col.key}
                    style={{ width: col.width }}
                    className={`py-2 px-3 border-r border-slate-200 last:border-r-0 ${
                      col.align === 'center'
                        ? 'text-center'
                        : col.align === 'right'
                        ? 'text-right'
                        : 'text-left'
                    }`}
                  >
                    {col.header}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200">
              {tableData.rows.map((row, rIdx) => (
                <tr
                  key={rIdx}
                  className={`hover:bg-slate-50/50 ${
                    rIdx % 2 === 1 ? 'bg-slate-50/40' : 'bg-white'
                  }`}
                >
                  {tableData.columns.map((col) => (
                    <td
                      key={col.key}
                      className={`py-2 px-3 border-r border-slate-200 last:border-r-0 text-slate-800 font-medium ${
                        col.align === 'center'
                          ? 'text-center'
                          : col.align === 'right'
                          ? 'text-right font-mono'
                          : 'text-left'
                      }`}
                    >
                      {row[col.key]}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      )}

      {/* 3. Performance Trend & Chart Summary */}
      {chartSummary && chartSummary.items.length > 0 && (
        <section className="doc-section-card border border-slate-200 rounded-lg p-3 bg-white space-y-2 avoid-break">
          <div className="flex items-center justify-between border-b border-slate-200 pb-1.5 doc-section-heading">
            <h4 className="text-[11px] font-bold text-[#0A3622] uppercase tracking-wider">
              {chartSummary.title}
            </h4>
            {chartSummary.description && (
              <span className="text-[10px] text-slate-500 italic">
                {chartSummary.description}
              </span>
            )}
          </div>
          <div className="space-y-2 pt-1">
            {chartSummary.items.map((item, idx) => (
              <div key={idx} className="space-y-1">
                <div className="flex items-center justify-between text-[10.5px]">
                  <span className="font-semibold text-slate-800">{item.label}</span>
                  <span className="font-bold font-mono text-[#0A3622]">
                    {item.value || `${item.percentage}%`}
                  </span>
                </div>
                <div className="w-full bg-slate-100 rounded-full h-2 overflow-hidden border border-slate-200">
                  <div
                    className="bg-[#0A3622] h-full rounded-full transition-all duration-300"
                    style={{ width: `${Math.min(100, Math.max(0, item.percentage))}%` }}
                  />
                </div>
              </div>
            ))}
          </div>
        </section>
      )}

      {/* 4. Custom Sections (e.g. key-value pairs or text blocks) */}
      {customSections &&
        customSections.map((sec, sIdx) => (
          <section
            key={sIdx}
            className="doc-section-card border border-slate-200 rounded-lg p-3 bg-white space-y-2 avoid-break"
          >
            <h4 className="text-[11px] font-bold text-[#0A3622] uppercase tracking-wider border-b border-slate-200 pb-1 doc-section-heading">
              {sec.title}
            </h4>
            {sec.keyValues && (
              <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 pt-1">
                {sec.keyValues.map((kv, kIdx) => (
                  <div key={kIdx} className="bg-slate-50 p-2 rounded border border-slate-200 text-xs">
                    <span className="text-[9.5px] font-bold uppercase text-slate-500 block">
                      {kv.label}
                    </span>
                    <span className="font-semibold text-slate-900">{kv.value}</span>
                  </div>
                ))}
              </div>
            )}
            {sec.content && <div className="text-xs text-slate-700">{sec.content}</div>}
          </section>
        ))}

      {/* 5. Recommendations & Faculty Observations */}
      {recommendations && recommendations.length > 0 && (
        <section className="bg-amber-50/60 border border-amber-200 rounded-lg p-3 text-xs space-y-1.5 avoid-break">
          <h4 className="text-[11px] font-bold uppercase tracking-wider text-amber-900 flex items-center gap-1.5 doc-section-heading">
            <span className="w-1.5 h-1.5 rounded-full bg-amber-600 inline-block" />
            Faculty Observations &amp; Academic Recommendations:
          </h4>
          <ul className="list-disc list-inside space-y-0.5 text-amber-950 text-[11px] pl-1 leading-relaxed">
            {recommendations.map((rec, rIdx) => (
              <li key={rIdx}>{rec}</li>
            ))}
          </ul>
        </section>
      )}
    </DocumentLayout>
  );
};
